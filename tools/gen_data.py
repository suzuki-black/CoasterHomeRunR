def sprite_bytes(rows):
    # 16×16 は 8×8 を 左上・左下・右上・右下 の順に並べる
    out = []
    for x0 in (0, 8):
        for y in range(16):
            b = 0
            for x in range(8):
                if rows[y][x0 + x] == '#':
                    b |= 0x80 >> x
            out.append(b)
    return out


def carray(name, ctype, vals, per=16):
    lines = [f'const {ctype} {name}[{len(vals)}] = {{']
    for i in range(0, len(vals), per):
        lines.append('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main(out):
    sin = [round(math.sin(2 * math.pi * i / 256) * 256) for i in range(320)]

    chars = sorted(FONT)
    font = []
    fmap = [0xFF] * 96
    for n, ch in enumerate(chars):
        fmap[ord(ch) - 0x20] = n
        for row in FONT[ch]:
            font.append(sum((1 << (2 - i)) for i, c in enumerate(row) if c == '#'))

    tro = [c for row in trolley_base() for c in row]
    dmg = []
    for level in TROLLEY_DAMAGE:
        for (x, y, w, h, c) in level:
            dmg += [x, y, w, h, c]
        dmg.append(0xFF)               # 段の区切り

    # 逆数表: m = 256..511 について round(2^24 / m)(m=256 は 65535 に丸める)。raster.s の傾き計算
    rtab = [min(65535, round((1 << 24) / m)) for m in range(256, 512)]

    spr = []
    for s in SPRITES:
        spr += sprite_bytes(s)

    with open(out, 'w') as f:
        f.write('/* tools/gen_data.py が生成。手で編集しない */\n')
        f.write('#include "engine.h"\n\n')
        f.write(carray('sin_tab', 'i16', sin) + '\n\n')
        f.write(carray('font35', 'u8', font) + '\n\n')
        f.write(carray('font35_map', 'u8', fmap) + '\n\n')
        f.write(carray('spr_patterns', 'u8', spr) + '\n\n')
        f.write(carray('recip9', 'u16', rtab) + '\n\n')
        f.write(carray('trolley_img', 'u8', tro) + '\n\n')
        f.write(carray('trolley_dmg', 'u8', dmg) + '\n')


if __name__ == '__main__':
    main(sys.argv[1])
