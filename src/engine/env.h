/* env.h — 環境ポリゴン
 *
 * 地形の処理(env.c)は、マッパーのセグメント 5 に置く「地形モジュール」(ステージごとに、その面の地形の処理だけを入れる。ステージの始めに ROM から読み込む)。
 * 呼ぶときだけページ2をセグメント 5 に切り替える(sys.s の env_build / env_draw が切り替えて呼び、戻す)。
 * モジュールの中からはゲームモジュール(ページ2のセグメント 1)の定数は読めないので、地形の区間と乱数の種は
 * 常駐部の g_env_zones / g_env_seed に写してから env_build を呼ぶ。
 */
#ifndef ENV_H
#define ENV_H
#include "engine.h"

/* 地形の種類(ステージの zones で区間ごとに指定する) */
enum { K_CAVE,     /* 炭鉱の坑道(ステージ 1 のパレット) */
       K_EXIT,     /* 洞窟の出口(屋外のパレットで描く坑道) */
       K_LAKE,     /* 地底湖(大きな空洞の水面。コースターごと筏に乗って渡る) */
       K_FOREST,   /* 森 */
       K_TOWN,     /* 町(両側に家並み) */
       K_HOME,     /* 村の入り口(通りの突き当たりに村の門) */
       K_PARK,     /* 遊園地の中のコースターの高架(下は空いていて、遠くにテントや観覧車) */
       K_HILL,     /* 遊園地の外の丘の下り坂(なぜかレールが敷いてある) */
       K_AIR,      /* 宙に飛び出したところ(何も描かない) */
       K_PARKSIDE, /* 遊園地の柵沿い(左に縞の柵と、その上に見える出し物、右は下っていく草の斜面) */
       K_BRIDGE,   /* 海にかかる鉄橋(左右と頭上を鉄骨のトラスで囲む。下は海) */
       K_GLADE,    /* 森の中の木漏れ日の空き地(両側が低い木立まで開け、日の当たる草地に花と切り株) */
       K_STREAM,   /* 森の小川にかかる丸太橋(足元は丸太、左右は空を映す水面) */
       K_HOLLOW,   /* 中が空洞の倒木のトンネル(入口と出口に丸太の切り口) */
       K_SHRINE,   /* 森の中の苔むした祠(左に祠、線路をまたぐ鳥居) */
       K_FAIR,     /* 祭りの町の屋台と提灯の通り(両側に切れ目の無い店、屋台、通りをまたぐ提灯の綱) */
       K_CANAL,    /* 町の運河にかかる石の橋(欄干の外は水面、遠くに川沿いの家並み) */
       K_PLAZA,    /* 町の噴水の広場(四方に開けた石畳、遠くに建物、噴水と街灯) */
       K_GATE,     /* 町の門(石の門塔をくぐるトンネル。入口と出口に門塔の正面) */
       K_PADDY,    /* 村の田んぼ(水を張った田に苗の列とあぜ、かかし) */
       K_MILL,     /* 村の水車(左は田んぼ、右に回る水車と水車小屋) */
       K_FALLS,    /* 地底湖の滝(左の岩壁を流れ落ちる滝と滝つぼのしぶき) */
       K_CRYSTAL,  /* 地底湖の光る結晶の洞(少し狭く低い洞。壁と天井に光る結晶、明るい水面) */
       K_WRECK,    /* 地底湖に沈んだトロッコの残骸(ひっくり返って半分沈んだトロッコ、折れたレール、浮いた板) */
       K_ARCH,     /* 地底湖の岩の門(湖の上の狭い天然の岩のトンネル。鍾乳石が密に下がる) */
       K_STALLS,   /* 遊園地の外の丘の、屋台の並ぶ道(縞の日よけの屋台、柱に張った提灯の綱) */
       K_LOOP,     /* 遊園地の柵沿いの、右の斜面の下のジェットコースターの宙返りの輪(コースターが回る) */
       K_CASTLE,   /* 遊園地の柵沿いの、右の斜面の向こうの丘の上のお城(白い城壁と赤い屋根の塔、夕暮れの花火) */
       K_ARCHBR,   /* 海の鉄橋のアーチ橋の区間(頭上に弧を描くアーチと吊り材。28m の径間をくり返す) */
       K_COUNT };

#define ENV_NR        11          /* リングの数 - 1(前 5 + 後ろ 5 + 仮リング)。env.c の NR と同じ */
#define ENV_ZONES_MAX 32

/* s = カメラのレール位置(1/64m)、look = 視線の相対ヨー(0 前 / 128 後ろ。下位 8 ビット)。
 * 引数はどちらも 16 ビットにしてレジスタ(HL, DE)で渡す(スタックで渡すと、切り替えを挟む sys.s の中継でずれる) */
void env_draw(u16 s, u16 look);
/* ステージ開始時(レール表を作った後)に、断面・色・飾りを乱数の種 g_env_seed と地形の区間 g_env_zones で作る */
void env_build(void);
extern u8  g_env_zones[ENV_ZONES_MAX];   /* 先頭 = レールの色、以降 (このリングまで, 種類) の組。0xFF まで */
extern u16 g_env_seed;
/* 周回区間(Stage.loops の写し)。地形モジュールは終わりの前後 LOOP_K 本のリングを始まりの前後と同じにする */
#define ENV_LOOPS_MAX 9
#define LOOP_K 6
extern u8  g_env_loops[ENV_LOOPS_MAX];
extern u8  g_seg2;

/* 地形モジュールの中の本体(ページ2 = セグメント 5 のときだけ呼べる。常駐部の env_build / env_draw 経由で呼ぶ) */
void envm_build(void);
void envm_draw(u16 s, u16 look);

#endif
